import { useEffect, useMemo, useState } from 'react';
import { ArrowDownUp, Download, Eye, FileSpreadsheet, FileText, Filter, History, ListChecks } from 'lucide-react';
import Icon from '../../components/Icon';
import { Badge, EmptyRow, Page, PageHeader, PageState, SearchBox } from '../../components/ui';
import { usePageData } from '../../hooks/usePageData';
import { reportService, type GeneratedReport, type ReportFilters, type ReportPreview } from '../../services/reportService';
import { ArchonAlert } from '../../utils/alerts';
import { isoDateFromToday, phpMjYgiA } from '../../utils/format';
import { ClearFilters, DateRangeFilter, FilterCount, FilterSelect, SortTh, distinct, inDateRange, is, matchesText, useFilters, useTableView } from '../../components/TableControls';
import '../../styles/time-attendance.css';

const PREVIEW_ROWS = 200;

function fileSize(bytes: number): string {
    return bytes >= 1048576 ? `${(bytes / 1048576).toFixed(1)} MB` : `${Math.max(1, Math.round(bytes / 1024))} KB`;
}

/** Reports > Generated Reports: every PDF / Excel generated before, opened again exactly as it was generated. */
function GeneratedReports({ reports, loading, error, onRetry, typeLabel }: {
    reports: GeneratedReport[] | null;
    loading: boolean;
    error: string | null;
    onRetry: () => void;
    typeLabel: (key: string) => string;
}) {
    const filters = useFilters({ search: '', format: '', type: '', by: '', from: '', to: '' });
    const f = filters.values;
    const list = reports ?? [];
    const hv = useTableView(list, r => is(f.format, r.format) && is(f.type, r.report_type) && is(f.by, r.generated_by_name) && inDateRange(r.created_at, f.from, f.to)
        && matchesText(f.search, r.report_no, r.title, typeLabel(r.report_type), r.period_label, r.generated_by_name), {
        no: r => r.report_no, report: r => r.title, period: r => r.period_label, format: r => r.format, records: r => r.record_count,
        by: r => r.generated_by_name, created: r => r.created_at,
    });
    const shown = hv.rows;
    return (
        <div className="card hover-card" id="generatedReportsCard" style={{ marginTop: '1.5rem' }}>
            <div className="card-header">
                <div>
                    <h3 className="card-title"><Icon as={History} /> Generated Reports</h3>
                    <p className="card-subtitle">Every report generated in the system, kept exactly as it was generated</p>
                </div>
                <Badge variant="badge-info">{list.length} report{list.length === 1 ? '' : 's'}</Badge>
            </div>
            <div className="card-body">
                <div className="toolbar-left">
                    <SearchBox value={f.search} onChange={filters.set('search')} placeholder="Search report no., report, period, generated by..." />
                    <FilterSelect id="rpHistoryFormat" label="Formats" value={f.format} onChange={filters.set('format')} options={[{ value: 'pdf', label: 'PDF' }, { value: 'xlsx', label: 'Excel' }]} />
                    <FilterSelect id="rpHistoryType" label="Report Types" value={f.type} onChange={filters.set('type')}
                        options={distinct(list, r => r.report_type).map(k => ({ value: k, label: typeLabel(k) }))} />
                    <FilterSelect id="rpHistoryBy" label="Generated By" allLabel="Anyone" value={f.by} onChange={filters.set('by')} options={distinct(list, r => r.generated_by_name)} />
                    <DateRangeFilter id="rpHistoryDate" label="Generated" from={f.from} to={f.to} onFrom={filters.set('from')} onTo={filters.set('to')} />
                    <ClearFilters id="rpHistoryClear" active={filters.active} onClear={filters.clear} />
                    <FilterCount shown={shown.length} total={list.length} />
                </div>
            </div>
            <PageState loading={loading && !reports} error={error} onRetry={onRetry} />
            <div className="card-body no-padding">
                <table className="data-table" id="generatedReportsTable">
                    <thead><tr><SortTh view={hv} k="no">Report No.</SortTh><SortTh view={hv} k="report">Report</SortTh><SortTh view={hv} k="period">Period</SortTh><SortTh view={hv} k="format">Format</SortTh><SortTh view={hv} k="records">Records</SortTh><SortTh view={hv} k="by">Generated By</SortTh><SortTh view={hv} k="created">Generated On</SortTh><th>Actions</th></tr></thead>
                    <tbody>
                        {!shown.length ? (
                            <EmptyRow colSpan={8}>{list.length ? 'No records found. Try other filters or clear them.' : 'No reports generated yet. Click Generate PDF or Generate Excel above; the file is kept here.'}</EmptyRow>
                        ) : shown.map(r => (
                            <tr className="hover-row" key={r.id} data-id={r.id}>
                                <td className="att-nowrap"><strong>{r.report_no}</strong></td>
                                <td>{r.title}<div className="att-muted">{typeLabel(r.report_type)}</div></td>
                                <td>{r.period_label}</td>
                                <td><Badge variant={r.format === 'pdf' ? 'badge-danger' : 'badge-success'}>{r.format === 'pdf' ? 'PDF' : 'Excel'}</Badge><div className="att-muted">{fileSize(r.file_size)}</div></td>
                                <td className="att-num">{r.record_count}</td>
                                <td>{r.generated_by_name ?? <span className="att-muted">—</span>}</td>
                                <td className="att-nowrap">{phpMjYgiA(r.created_at)}</td>
                                <td className="att-nowrap">
                                    {r.format === 'pdf' && (
                                        <a className="table-action-btn" title="View" aria-label={`View ${r.report_no}`} href={reportService.storedUrl(r.id, true)} target="_blank" rel="noopener"><Icon as={Eye} /></a>
                                    )}
                                    <a className="table-action-btn" title="Download" aria-label={`Download ${r.report_no}`} href={reportService.storedUrl(r.id)}><Icon as={Download} /></a>
                                </td>
                            </tr>
                        ))}
                    </tbody>
                </table>
            </div>
        </div>
    );
}

/**
 * Reports: choose the report, its date range, department / position / status
 * filters and sorting; preview the live database records, then generate the
 * same report as PDF or Excel.
 */
export default function ReportsPage() {
    const { data: opts, loading, error, retry } = usePageData(reportService.options);
    const history = usePageData(reportService.history);
    const typeLabel = (key: string) => opts?.types.find(t => t.key === key)?.label ?? key;
    const [f, setF] = useState<ReportFilters>({ type: 'applicant', period: 'month', from: '', to: '', department: '', position: '', status: '', sort: 'applied_at', order: 'desc' });
    const [preview, setPreview] = useState<ReportPreview | null>(null);
    const [busy, setBusy] = useState(false);
    // Preview cells are display text; numbers / dates sort by their underlying value where the text allows it.
    const previewSort = (key: string) => (r: Record<string, string>) => {
        const v = r[key] ?? '';
        const n = Number(v.replace(/[^0-9.-]/g, ''));
        const kind = preview?.columns.find(c => c.key === key)?.kind;
        if (kind && ['int', 'money', 'hours', 'score'].includes(kind) && v !== '' && Number.isFinite(n)) return n;
        if (kind === 'date' || kind === 'datetime') { const t = Date.parse(v); return Number.isNaN(t) ? v : t; }
        return v;
    };
    const pv = useTableView(preview?.rows, () => true, Object.fromEntries((preview?.columns ?? []).map(c => [c.key, previewSort(c.key)])));
    const def = opts?.types.find(t => t.key === f.type);
    const deptId = opts?.departments.find(d => d.name === f.department)?.id;
    const positions = useMemo(() => (opts?.positions ?? []).filter(p => !f.department || p.department_id === deptId), [opts, f.department, deptId]);

    // A different report: its own defaults (status / sort), and no stale preview.
    useEffect(() => {
        if (!def) return;
        setF(x => ({ ...x, status: '', sort: def.default_sort[0], order: def.default_sort[1], period: !def.all_dates && x.period === 'all' ? 'month' : x.period }));
        setPreview(null);
    }, [f.type]); // eslint-disable-line react-hooks/exhaustive-deps

    const set = (k: keyof ReportFilters) => (e: React.ChangeEvent<HTMLInputElement | HTMLSelectElement>) => {
        setF(x => ({ ...x, [k]: e.target.value, ...(k === 'department' ? { position: '' } : {}) }));
        setPreview(null);
    };

    const check = async (): Promise<boolean> => {
        if (f.period === 'custom' && (!f.from || !f.to)) { await ArchonAlert.warning('Please select the start and end of the custom date range.', { title: 'Date Range' }); return false; }
        if (f.period === 'custom' && f.to < f.from) { await ArchonAlert.warning('The end date cannot be earlier than the start date.', { title: 'Date Range' }); return false; }
        return true;
    };

    const runPreview = async () => {
        if (!(await check())) return;
        setBusy(true);
        try {
            setPreview((await reportService.preview(f)).report);
        } catch (e) {
            await ArchonAlert.error(e instanceof Error ? e.message : 'The report could not be generated.');
        } finally {
            setBusy(false);
        }
    };
    const generate = async (format: 'pdf' | 'xlsx') => {
        if (!(await check())) return;
        window.location.href = reportService.fileUrl(f, format);
        // The file downloads in place; the new entry of Generated Reports appears once it is kept.
        for (const ms of [2500, 7000]) window.setTimeout(() => void history.reload().catch(() => undefined), ms);
    };

    const isDateSort = (k: string) => ['applied_at', 'posted_at', 'date_hired', 'start_date', 'created_at', 'offer_date'].includes(k);

    return (
        <Page id="reports">
            <PageHeader title="Reports" subtitle="Generate reports from the live HRMS database as PDF or Excel" />
            <PageState loading={loading} error={error} onRetry={retry} />
            {opts && def && (
                <>
                    <div className="card hover-card" id="reportConfigCard">
                        <div className="card-header"><h3 className="card-title"><Icon as={Filter} /> Report Settings</h3></div>
                        <div className="card-body">
                            <div className="att-filters" style={{ marginBottom: 0 }}>
                                <div className="att-field">
                                    <label htmlFor="rpType">Report Type</label>
                                    <select className="form-select" id="rpType" value={f.type} onChange={set('type')}>
                                        {opts.types.map(t => <option key={t.key} value={t.key}>{t.label}</option>)}
                                    </select>
                                </div>
                                <div className="att-field">
                                    <label htmlFor="rpPeriod">Date ({def.date_label})</label>
                                    <select className="form-select" id="rpPeriod" value={f.period} onChange={set('period')}>
                                        {opts.periods.filter(p => p.key !== 'all' || def.all_dates).map(p => <option key={p.key} value={p.key}>{p.label}</option>)}
                                    </select>
                                </div>
                                {f.period === 'custom' && <>
                                    <div className="att-field">
                                        <label htmlFor="rpFrom">From</label>
                                        <input type="date" className="form-input" id="rpFrom" value={f.from} max={f.to || undefined} onChange={set('from')} />
                                    </div>
                                    <div className="att-field">
                                        <label htmlFor="rpTo">To</label>
                                        <input type="date" className="form-input" id="rpTo" value={f.to} min={f.from || undefined} max={isoDateFromToday(366)} onChange={set('to')} />
                                    </div>
                                </>}
                                <div className="att-field">
                                    <label htmlFor="rpDept">Department</label>
                                    <select className="form-select" id="rpDept" value={f.department} onChange={set('department')}>
                                        <option value="">All Departments</option>
                                        {opts.departments.map(d => <option key={d.id} value={d.name}>{d.name}</option>)}
                                    </select>
                                </div>
                                <div className="att-field">
                                    <label htmlFor="rpPosition">Position</label>
                                    <select className="form-select" id="rpPosition" value={f.position} onChange={set('position')}>
                                        <option value="">All Positions</option>
                                        {positions.map(p => <option key={p.id} value={p.title}>{p.title}</option>)}
                                    </select>
                                </div>
                                {def.statuses && (
                                    <div className="att-field">
                                        <label htmlFor="rpStatus">{def.status_label}</label>
                                        <select className="form-select" id="rpStatus" value={f.status} onChange={set('status')}>
                                            <option value="">All</option>
                                            {def.statuses.map(s => <option key={s} value={s}>{s}</option>)}
                                        </select>
                                    </div>
                                )}
                                <div className="att-field">
                                    <label htmlFor="rpSort">Sort By</label>
                                    <select className="form-select" id="rpSort" value={f.sort} onChange={set('sort')}>
                                        {def.sorts.map(s => <option key={s.key} value={s.key}>{s.label}</option>)}
                                    </select>
                                </div>
                                <div className="att-field">
                                    <label htmlFor="rpOrder">Order</label>
                                    <select className="form-select" id="rpOrder" value={f.order} onChange={set('order')}>
                                        <option value="asc">{isDateSort(f.sort) ? 'Oldest to Newest' : 'Ascending (A-Z, 0-9)'}</option>
                                        <option value="desc">{isDateSort(f.sort) ? 'Newest to Oldest' : 'Descending (Z-A, 9-0)'}</option>
                                    </select>
                                </div>
                            </div>
                            <div style={{ display: 'flex', gap: '0.5rem', flexWrap: 'wrap', marginTop: '1.25rem' }}>
                                <button className="btn btn-outline" id="rpPreviewBtn" disabled={busy} onClick={() => void runPreview()}><Icon as={Eye} /> Preview</button>
                                <button className="btn btn-primary" id="rpPdfBtn" onClick={() => void generate('pdf')}><Icon as={FileText} /> Generate PDF</button>
                                <button className="btn btn-success" id="rpXlsxBtn" onClick={() => void generate('xlsx')}><Icon as={FileSpreadsheet} /> Generate Excel</button>
                            </div>
                        </div>
                    </div>

                    {preview && (
                        <div className="card hover-card" id="reportPreviewCard" style={{ marginTop: '1.5rem' }}>
                            <div className="card-header">
                                <div>
                                    <h3 className="card-title" id="rpPreviewTitle">{preview.title.toUpperCase()}</h3>
                                    <p className="card-subtitle">Period: <strong>{preview.period_label}</strong> · Generated by {preview.generated_by} · {preview.generated_at}</p>
                                </div>
                                <Badge variant="badge-info"><span id="rpCount">{preview.count}</span>&nbsp;record{preview.count === 1 ? '' : 's'}</Badge>
                            </div>
                            <div className="card-body">
                                <div className="modal-info-grid" id="rpFiltersApplied" style={{ marginBottom: '1rem' }}>
                                    {Object.entries(preview.filters).map(([k, v]) => (
                                        <div className="info-item" key={k}><div className="info-label">{k === 'Sort' ? <><Icon as={ArrowDownUp} /> Sorting</> : k}</div><div className="info-value">{v}</div></div>
                                    ))}
                                </div>
                            </div>
                            <div className="card-body no-padding">
                                <table className="data-table" id="reportPreviewTable">
                                    <thead><tr><th>#</th>{preview.columns.map(c => <SortTh view={pv} k={c.key} key={c.key}>{c.label}</SortTh>)}</tr></thead>
                                    <tbody>
                                        {!preview.rows.length ? <EmptyRow colSpan={preview.columns.length + 1}>No records match the selected filters.</EmptyRow>
                                            : pv.rows.slice(0, PREVIEW_ROWS).map((r, i) => (
                                                <tr className="hover-row" key={i}>
                                                    <td className="att-muted">{i + 1}</td>
                                                    {preview.columns.map(c => <td key={c.key} className={['int', 'money', 'hours', 'score'].includes(c.kind) ? 'att-num' : undefined}>{r[c.key] || <span className="att-muted">—</span>}</td>)}
                                                </tr>
                                            ))}
                                    </tbody>
                                </table>
                                {preview.count > PREVIEW_ROWS && <p className="att-note" style={{ padding: '0.75rem 1rem', margin: 0 }}><Icon as={ListChecks} /> Showing the first {PREVIEW_ROWS} of {preview.count} records; the PDF and Excel files contain all of them.</p>}
                            </div>
                        </div>
                    )}

                    <GeneratedReports reports={history.data?.reports ?? null} loading={history.loading} error={history.error}
                        onRetry={history.retry} typeLabel={typeLabel} />
                </>
            )}
        </Page>
    );
}
